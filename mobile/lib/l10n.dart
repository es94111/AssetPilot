String normalizeAppLocale(String? value) {
  final s = (value ?? '').trim().replaceAll('_', '-').toLowerCase();
  if (s.isEmpty) return 'zh-TW';
  if (s == 'zh-cn' ||
      s == 'zh-hans' ||
      s.startsWith('zh-cn-') ||
      s.startsWith('zh-hans-') ||
      s.startsWith('zh-sg')) {
    return 'zh-CN';
  }
  if (s.startsWith('zh')) return 'zh-TW';
  if (s.startsWith('en')) return 'en';
  if (s.startsWith('es')) return 'es';
  if (s.startsWith('ar')) return 'ar';
  if (s.startsWith('fr')) return 'fr';
  if (s.startsWith('hi')) return 'hi';
  if (s.startsWith('pt')) return 'pt-BR';
  if (s.startsWith('ru')) return 'ru';
  if (s.startsWith('ko')) return 'ko';
  return 'zh-TW';
}

Locale flutterLocaleFor(String locale) => switch (normalizeAppLocale(locale)) {
      'zh-TW' => const Locale.fromSubtags(languageCode: 'zh', scriptCode: 'Hant', countryCode: 'TW'),
